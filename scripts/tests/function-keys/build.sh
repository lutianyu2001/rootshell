#!/usr/bin/env bash
# Assemble FKeyTest.swift from the function-key code as it stands in the repo:
# KeyID.functionKeyNumber, Ghostty.TerminalView.functionKeyHIDUsage and
# functionKeySequence, and KeyModifiers. Only UIKeyboardHIDUsage is stubbed,
# with UIKit's raw values for F1-F12.
set -eu
cd "$(dirname "$0")"
R=${1:-$(git rev-parse --show-toplevel)}
{
  echo "// Generated by build.sh from $R"
  echo "enum UIKeyboardHIDUsage: Int {"
  echo "    case keyboardF1 = 0x3A, keyboardF2, keyboardF3, keyboardF4, keyboardF5, keyboardF6"
  echo "    case keyboardF7, keyboardF8, keyboardF9, keyboardF10, keyboardF11, keyboardF12"
  echo "}"
  awk '/^struct KeyModifiers: OptionSet/{p=1} p{print} p&&/^}/{exit}' "$R/rootshell/UI/Keyboard/KeyboardButton.swift"
  echo "enum KeyID {"
  awk '/static func functionKeyNumber/{p=1} p{print} p&&/^    }$/{exit}' "$R/rootshell/UI/Keyboard/KeyboardToolbarCustomization.swift"
  echo "}"
  echo "enum Ghostty { enum TerminalView {"
  awk '/static func functionKeyHIDUsage/{p=1} /Navigation keys whose modified forms/{exit} p{print}' "$R/rootshell/UI/Terminal/TerminalView.swift"
  echo "} }"
  cat main.swift
} > FKeyTest.swift
