//
//  AppIconMark.swift
//  rootshell
//
//  The mark of an app icon as a vector silhouette. The selectable icons draw
//  one of four marks; each was traced into polygons from that icon's own
//  layers (AppIcon.icon, AltIcons/). Coordinates are fractions of the mark's
//  bounding box, x across and y down, and the loops fill by the even-odd
//  rule, so a loop inside another is a hole.
//

import SwiftUI

struct AppIconMark: Shape {
    enum Kind {
        /// The # with roots of the default icon and its recolored variants.
        case hash
        /// The #_ of the Underscore icon.
        case underscore
        /// The rooted monitor of the Original icon.
        case original
        /// The radical sign over a >_ prompt of the Radical icons. The icons
        /// cut the sign off at their edge; here it ends in round caps.
        case radical
    }

    let kind: Kind

    /// The mark's size when fitted into a square of the given side.
    func size(fitting side: CGFloat) -> CGSize {
        let ratio = kind.aspectRatio
        return ratio < 1 ? CGSize(width: side * ratio, height: side) : CGSize(width: side, height: side / ratio)
    }

    func path(in rect: CGRect) -> Path {
        // Fit the mark into rect without stretching it, centered.
        let ratio = kind.aspectRatio
        let height = min(rect.height, rect.width / ratio)
        let width = height * ratio
        let origin = CGPoint(x: rect.midX - width / 2, y: rect.midY - height / 2)
        var path = Path()
        for loop in kind.loops {
            let points = stride(from: 0, to: loop.count, by: 2).map {
                CGPoint(x: origin.x + loop[$0] * width, y: origin.y + loop[$0 + 1] * height)
            }
            path.addLines(points)
            path.closeSubpath()
        }
        return path
    }
}

extension AppIconManager.AppIconVariant {
    /// The mark this icon draws.
    var mark: AppIconMark.Kind {
        switch self {
        case .defaultIcon, .black, .crt, .noBorder, .sixColors, .sixColorsDark:
            return .hash
        case .underscore:
            return .underscore
        case .original:
            return .original
        case .radicalSolarizedDark, .radicalSolarizedLight, .radicalDracula, .radicalNord,
             .radicalGruvboxDark, .radicalTokyoNight, .radicalCatppuccin, .radicalBases,
             .radicalMonoLight, .radicalMonokai, .radicalMonoDark, .radicalRosePine:
            return .radical
        }
    }
}

